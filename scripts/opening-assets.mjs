// Generate src/opening/assets.ts from assets/opening/manifest.json (Sol's opening deliveries).
// Usage: node scripts/opening-assets.mjs
// Assets are keyed by id without the version suffix (op-bg05-hatch-lit-v2 -> op-bg05-hatch-lit), so a new revision
// replaces the old one without touching the player. Every PNG must match its manifest SHA-256 and size; build.mjs
// checks the same again on every build.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const manifest = JSON.parse(await readFile('assets/opening/manifest.json', 'utf8'));
const sha = b => createHash('sha256').update(b).digest('hex');
const key = id => id.replace(/-v\d+$/, '');
const seen = new Set(), lines = [], table = [], meta = [];
for (const a of manifest.assets) {
  const bytes = await readFile(a.file);
  if (sha(bytes) !== a.sha256) throw new Error(`Hash mismatch: ${a.id}`);
  if (bytes.readUInt32BE(16) !== a.w || bytes.readUInt32BE(20) !== a.h) throw new Error(`Size mismatch: ${a.id}`);
  const k = key(a.id);
  if (seen.has(k)) throw new Error(`Two revisions of ${k} in the manifest`);
  seen.add(k);
  const name = 'o' + a.id.replace(/[^a-z0-9]/gi, '_');
  const place = a.place ? `{ layer: '${key(a.place.layer)}', xy: [${a.place.xy.join(', ')}] }` : 'null';
  lines.push(`import ${name} from '../../${a.file}';`);
  table.push(`  '${k}': ${name},`);
  meta.push(`  '${k}': { w: ${a.w}, h: ${a.h}, place: ${place}, anchor: ${a.anchor ? `[${a.anchor.join(', ')}]` : 'null'} },`);
}
const out = `/**
 * Sol's opening plates (${manifest.assets.length} indexed PNG), inlined by esbuild as data URLs, keyed by id without the
 * version suffix. Generated by scripts/opening-assets.mjs from assets/opening/manifest.json; build.mjs verifies every
 * hash. Images are decoded when a playback starts and dropped with it.
 */
${lines.join('\n')}

export const OPENING_ASSET_URLS: Record<string, string> = {
${table.join('\n')}
};
/** Size, placement on another layer (top-left, art pixels) and foot anchor, from the manifest. */
export const OPENING_ASSET_META: Record<string, { w: number; h: number; place: { layer: string; xy: [number, number] } | null; anchor: [number, number] | null }> = {
${meta.join('\n')}
};

export type OpeningArt = Record<string, HTMLImageElement>;

/** Decode every plate; null when any fails, and the animatic keeps its placeholder painters. */
export async function loadOpeningArt(): Promise<OpeningArt | null> {
  try {
    const entries = await Promise.all(Object.entries(OPENING_ASSET_URLS).map(async ([id, src]) => {
      const image = new Image(); image.src = src; await image.decode(); return [id, image] as const;
    }));
    return Object.fromEntries(entries);
  } catch (error) {
    console.error('Opening art failed to decode; showing the placeholder frames.', error);
    return null;
  }
}
`;
await writeFile('src/opening/assets.ts', out);
console.log(`src/opening/assets.ts: ${manifest.assets.length} assets`);
